const DICTS = Object.fromEntries(
  Object.entries(BASE_DICTS).map(([code, dict]) => [code, { ...dict, ...(MENU[code] ?? {}), ...(PREVIEW[code] ?? {}) }]),
) as Record<LangCode, Dict>;

export function detectLanguage(): LangCode {
  if (typeof window === "undefined") return "en";
  const stored = window.localStorage.getItem(STORAGE_KEY) as LangCode | null;
  if (stored && DICTS[stored]) return stored;
  const nav = (window.navigator.languages?.[0] ?? window.navigator.language ?? "en").toLowerCase();
  const base = nav.split("-")[0] as LangCode;
  return DICTS[base] ? base : "en";
}

type I18nValue = {
  lang: LangCode;
  setLang: (l: LangCode) => void;
  t: (key: TranslationKey) => string;
};

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<LangCode>("en");

  useEffect(() => {
    const detected = detectLanguage();
    setLangState(detected);
    document.documentElement.lang = detected;
    document.documentElement.dir = RTL_LANGS.includes(detected) ? "rtl" : "ltr";
  }, []);

  const setLang = useCallback((l: LangCode) => {
    setLangState(l);
    if (typeof window !== "undefined") {
      window.localStorage.setItem(STORAGE_KEY, l);
      document.documentElement.lang = l;
      document.documentElement.dir = RTL_LANGS.includes(l) ? "rtl" : "ltr";
    }
  }, []);

  const t = useCallback(
    (key: TranslationKey) => DICTS[lang]?.[key] ?? en[key] ?? key,
    [lang],
  );

  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const ctx = useContext(I18nContext);
  if (ctx) return ctx;
  return { lang: "en", setLang: () => {}, t: (key: TranslationKey) => en[key] ?? key };
}
