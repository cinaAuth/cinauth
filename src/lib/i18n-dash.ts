const DASH: Record<string, Dict> = {
  es, ca, val, gl, eu, fr, de, pt, it, nl, pl, ru, uk, tr, sv, ar, hi, id, zh, ja, ko, vi, th,
};

export function dashLabel(lang: string, key: DashKey): string {
  return DASH[lang]?.[key] ?? DASH_EN[key];
}

/** Hook-friendly factory: const d = dashT(lang); d("title") */
export function dashT(lang: string) {
  return (key: DashKey) => dashLabel(lang, key);
}
